def _by_length() -> dict[int, list[str]]:
    table: dict[int, set[str]] = {}
    for word in (
        NOUNS
        + VERBS
        + ADJECTIVES
        + ADVERBS
        + FILLER
        + LONG
        + TWO
        + ONE
        + [w.lower() for w in FIRST_NAMES + LAST_NAMES + PLACES]
    ):
        if word.isascii() and word.isalpha():
            table.setdefault(len(word), set()).add(word.lower())
    return {length: sorted(words) for length, words in sorted(table.items())}


WORDS_BY_LENGTH = _by_length()
